#!/usr/bin/env bun
// omp-host.exe 构建编排：把 @oh-my-pi/pi-natives 的 .node 打成 tar.gz 内嵌进编译产物，
// 运行时由 loader 解包到 ~/.omp/natives/<版本>/。npm 发布的 pi-natives 里
// embedded-addon.js 是 null stub（embed 流程只存在于上游源码仓），直接 bun build --compile
// 得到的 exe 不含 native addon，在干净机器上必然启动失败。
// 流程照搬上游 ci-release-build-binaries.ts：embed → compile → reset（reset 放 finally，
// 避免 compile 失败后残留非 stub 的 embedded-addon.js，把 dev 模式误判成 compiled）。
import * as fs from "node:fs/promises";
import * as path from "node:path";
import {
	containsVersionSentinel,
	versionSentinelFor,
} from "../node_modules/@oh-my-pi/pi-natives/native/version-sentinel.js";

const repoRoot = path.join(import.meta.dir, "..");
const nativesPkgDir = path.join(repoRoot, "node_modules", "@oh-my-pi", "pi-natives");
const nativeDir = path.join(nativesPkgDir, "native");
const leafPkgDir = path.join(repoRoot, "node_modules", "@oh-my-pi", `pi-natives-${process.platform}-${process.arch}`);
const embeddedAddonPath = path.join(nativeDir, "embedded-addon.js");
const platformTag = `${process.platform}-${process.arch}`;
const archiveFilename = `embedded-addons.${platformTag}.tar.gz`;
const version = (JSON.parse(await Bun.file(path.join(nativesPkgDir, "package.json")).text())).version as string;

const candidates =
	process.arch === "x64"
		? [
				{ variant: "modern", filename: `pi_natives.${platformTag}-modern.node` },
				{ variant: "baseline", filename: `pi_natives.${platformTag}-baseline.node` },
			]
		: [{ variant: "default", filename: `pi_natives.${platformTag}.node` }];

async function resetEmbeddedAddon(): Promise<void> {
	await Bun.write(
		embeddedAddonPath,
		"// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY\n// See scripts/build-host.ts\n\n/** @type {null} */\nexport const embeddedAddon = null;\n",
	);
	await fs.rm(path.join(nativeDir, archiveFilename), { force: true });
}

async function embedNativeAddon(): Promise<void> {
	await resetEmbeddedAddon();
	const sentinel = versionSentinelFor(version);
	const entries: Record<string, Uint8Array> = {};
	const files: string[] = [];
	for (const { variant, filename } of candidates) {
		const sourcePath = path.join(leafPkgDir, filename);
		const file = Bun.file(sourcePath);
		if (!(await file.exists())) continue;
		// 必须 Node Buffer：Buffer.indexOf 支持子串搜索，Uint8Array.indexOf 只查单字节
		const bytes = await fs.readFile(sourcePath);
		if (!containsVersionSentinel(bytes, sentinel)) {
			throw new Error(
				`${sourcePath} 不含 @oh-my-pi/pi-natives@${version} 版本哨兵 \`${sentinel}\`，依赖版本不一致，请重装依赖`,
			);
		}
		entries[filename] = bytes;
		files.push(`\t{ variant: ${JSON.stringify(variant)}, filename: ${JSON.stringify(filename)}, size: ${bytes.length} },`);
	}
	if (files.length === 0) {
		throw new Error(`${leafPkgDir} 下没有任何 native addon（期望 ${candidates.map(c => c.filename).join(" 或 ")}）`);
	}
	const archiveBytes = await new Bun.Archive(entries, { compress: "gzip", level: 9 }).bytes();
	await Bun.write(path.join(nativeDir, archiveFilename), archiveBytes);
	await Bun.write(
		embeddedAddonPath,
		`// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY\n// See scripts/build-host.ts\n\nimport archivePath from ${JSON.stringify(`./${archiveFilename}`)} with { type: "file" };\n\nexport const embeddedAddon = {\n\tplatformTag: ${JSON.stringify(platformTag)},\n\tversion: ${JSON.stringify(version)},\n\tarchive: { format: "tar.gz", filename: ${JSON.stringify(archiveFilename)}, filePath: archivePath },\n\tfiles: [\n${files.join("\n")}\n\t],\n};\n`,
	);
	console.log(`已内嵌 native addon：${files.length} 个变体，tar.gz 共 ${(archiveBytes.length / 1024 / 1024).toFixed(1)} MB`);
}

await embedNativeAddon();
try {
	const build = Bun.spawnSync(
		[
			"bun",
			"build",
			"--compile",
			"--minify",
			"--external",
			"omp-legacy-pi-modules",
			"host/host.ts",
			"--outfile",
			"host-dist/omp-host.exe",
		],
		{ cwd: repoRoot, stdout: "inherit", stderr: "inherit" },
	);
	process.exitCode = build.exitCode ?? 1;
} finally {
	await resetEmbeddedAddon();
}
