// host/git-generated.ts: which changed files a diff should fold away.
import { describe, expect, test } from "bun:test";
import { GENERATED_DIRS, GENERATED_NAMES, GENERATED_SUFFIXES, generatedByName, isGenerated } from "../host/git-generated.ts";

describe("isGenerated", () => {
  test("lockfile by name", () => {
    expect(Object.keys(GENERATED_NAMES)).toContain("package-lock.json");
    expect(isGenerated("package-lock.json", [])).toBe(true);
    expect(isGenerated("web/app/bun.lock", [])).toBe(true);
  });

  test("minified and compiled output by suffix", () => {
    expect(GENERATED_SUFFIXES).toContain(".min.js");
    expect(isGenerated("dist/app.min.js", [])).toBe(true);
    expect(isGenerated("api/thing.pb.go", [])).toBe(true);
  });

  test("checked-in dependencies by directory", () => {
    expect(GENERATED_DIRS).toContain("node_modules");
    expect(isGenerated("node_modules/react/index.js", [])).toBe(true);
    expect(isGenerated("Pods/Foo/Bar.m", [])).toBe(true);
    // Only a whole path segment counts: a file merely named vendor stays normal.
    expect(isGenerated("vendor.txt", [])).toBe(false);
  });

  test("a generated header in the first five lines", () => {
    expect(isGenerated("src/a.ts", ["// Code generated by protoc-gen-ts. DO NOT EDIT.", "export {}"])).toBe(true);
    expect(isGenerated("src/b.ts", ["/*", " * @generated", " */"])).toBe(true);
    expect(isGenerated("src/c.cs", ["// <auto-generated>", "class C {}"])).toBe(true);
    // Past line five it no longer counts.
    expect(generatedByName("src/d.ts")).toBe(false);
    expect(isGenerated("src/d.ts", ["// a", "// b", "// c", "// d", "// e", "// @generated"])).toBe(false);
  });

  test("an ordinary file is not generated", () => {
    expect(isGenerated("ui-src/components/main/Composer.tsx", ["import { x } from 'y';"])).toBe(false);
  });
});
