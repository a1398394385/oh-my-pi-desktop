// i18n key parity gate: every key the UI asks for must exist in BOTH language
// bundles, and the two bundles must carry the same key set.
//
// Motivation: a missing key does not fail the build — i18next silently renders
// the raw key string ("settingsPage.exp.railDeviceDefault"), which is exactly
// the kind of defect that ships and is only noticed by looking at the screen
// (BUG: the music-reactivity device row shipped showing its raw key).
//
// Three checks:
//   1. Used keys: literal `t("...")` / `i18next.t("...")` call sites in ui-src
//      are collected and must exist in both bundles.
//   2. Defined keys: the en / zh-CN bundles are loaded through bun and walked.
//      The UI half of the comparison only runs when bun is available (it is —
//      the script is a bun script); the source half works under plain node.
//   3. Dynamic keys: keys composed at runtime — template literals containing
//      `${}` and string concatenation — cannot be resolved statically, so every
//      such call site in ui-src and host must be registered in
//      scripts/i18n-dynamic-keys.json with a reason. An unregistered site fails
//      the gate, and so does a registration whose call site is gone. Line
//      numbers in the baseline are informational: drift only prints a note.
//      Keys passed through a variable or ternary (`t(key)`) stay out of scope —
//      they are indirection over existing keys, not key text composed here.
//
// Baseline lifecycle: generated by --update (reasons are carried over per
// file+prefix and must be written by hand for new sites); lowering the site
// count also goes through --update.
//
// Usage: bun scripts/check-i18n-keys.ts [--update]   (or node, for the call-site half only)
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const baselineRel = "scripts/i18n-dynamic-keys.json";
const baselinePath = join(root, baselineRel);
const update = process.argv.includes("--update");

const SKIP_DIRS = ["node_modules", "dist", "out", "target"];

/** Visit every .ts/.tsx source under the given repo-relative roots. */
function walkSources(roots: string[], visit: (file: string, src: string) => void): void {
  for (const dir of roots) {
    const walk = (abs: string) => {
      for (const entry of readdirSync(abs)) {
        if (SKIP_DIRS.includes(entry)) continue;
        const full = join(abs, entry);
        if (statSync(full).isDirectory()) {
          walk(full);
          continue;
        }
        if (!/\.tsx?$/.test(entry)) continue;
        // i18n bundles are definitions, not call sites.
        if (full.includes(`${sep}i18n${sep}`)) continue;
        visit(full.slice(root.length + 1), readFileSync(full, "utf8"));
      }
    };
    walk(join(root, dir));
  }
}

/** Every literal key passed to t()/i18next.t() across the UI sources. */
function collectUsedKeys(): { key: string; file: string; line: number }[] {
  const out: { key: string; file: string; line: number }[] = [];
  walkSources(["ui-src"], (file, src) => {
    src.split("\n").forEach((line, idx) => {
      // Only literal keys: `t("a.b")`. Two shapes look literal but are not —
      // a partial prefix being concatenated (`t("a." + k)`) and a template
      // literal (`` t(`a.${k}`) ``). Neither is statically resolvable, so
      // blank out every such call before scanning for real literals.
      const literal = line
        // `t("..." + expr` / `t("..."+expr` — concatenations
        .replace(/\b(?:i18next\.)?t\(\s*"[^"]*"\s*\+[^)]*\)/g, " ")
        // `t("..." + expr)` where expr ends the call — catch-all for the above
        .replace(/\b(?:i18next\.)?t\(\s*`[^`]*`/g, " ");
      const re = /\b(?:i18next\.)?t\(\s*"([a-zA-Z0-9_]+(?:\.[a-zA-Z0-9_]+)*)"(?![+`])/g;
      let m: RegExpExecArray | null;
      while ((m = re.exec(literal)) !== null) {
        out.push({ key: m[1], file, line: idx + 1 });
      }
    });
  });
  return out;
}

/** Read a quoted string body starting at the opening quote; null when unterminated. */
function readString(src: string, start: number): { body: string; end: number } | null {
  const quote = src[start];
  for (let i = start + 1; i < src.length; i++) {
    if (src[i] === "\\") {
      i++;
      continue;
    }
    if (src[i] === quote) return { body: src.slice(start + 1, i), end: i + 1 };
  }
  return null;
}

/**
 * Keys composed at runtime: template literals with `${}` and string
 * concatenation. `prefix` is the static part before the composition (the whole
 * literal for concatenation). The leading boundary check keeps method names
 * ending in `t` (`setCount(`) out, and comment-only lines are skipped so prose
 * examples like `t()` do not register.
 */
function collectDynamicSites(): { file: string; line: number; prefix: string }[] {
  const out: { file: string; line: number; prefix: string }[] = [];
  const call = /(?<![\w$])(?:[A-Za-z_$][\w$]*\.)*t\(\s*/g;
  walkSources(["ui-src", "host"], (file, src) => {
    for (let m = call.exec(src); m; m = call.exec(src)) {
      const lineStart = src.lastIndexOf("\n", m.index) + 1;
      if (/^\s*(?:\/\/|\*|\/\*)/.test(src.slice(lineStart, m.index))) continue;
      const at = call.lastIndex;
      if (src[at] !== '"' && src[at] !== "`") continue;
      const arg = readString(src, at);
      if (!arg) continue;
      let prefix: string | null = null;
      if (src[at] === "`" && arg.body.includes("${")) {
        prefix = arg.body.slice(0, arg.body.indexOf("${"));
      } else if (src[at] === '"') {
        let next = arg.end;
        while (/\s/.test(src[next])) next++;
        if (src[next] === "+") prefix = arg.body;
      }
      if (prefix !== null) out.push({ file, line: src.slice(0, m.index).split("\n").length, prefix });
    }
  });
  return out;
}

type DynSite = { file: string; line: number; prefix: string };
type BaselineSite = DynSite & { reason: string };

function loadBaseline(): BaselineSite[] {
  const data = JSON.parse(readFileSync(baselinePath, "utf8")) as { sites?: BaselineSite[] };
  return data.sites ?? [];
}

const groupKey = (s: DynSite) => `${s.file}\0${s.prefix}`;

/** Flatten a nested bundle object into dotted key paths. */
function flatten(obj: unknown, prefix = ""): Set<string> {
  const out = new Set<string>();
  if (!obj || typeof obj !== "object") return out;
  for (const [k, v] of Object.entries(obj as Record<string, unknown>)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) {
      for (const sub of flatten(v, path)) out.add(sub);
    } else {
      out.add(path);
    }
  }
  return out;
}

/**
 * i18next plural suffixes (`key_one` / `key_other`) are resolved at lookup time,
 * not stored per-locale: zh has only `_other`, en has both. Comparing raw key
 * names would flag every pluralized string, so the plural family is collapsed to
 * its base key before the parity check.
 */
function collapsePlurals(keys: Set<string>): Set<string> {
  const out = new Set<string>();
  for (const key of keys) out.add(key.replace(/_(zero|one|two|few|many|other)$/, ""));
  return out;
}

// Bundles are statically importable (fixed paths), and bun compiles the TS
// locale files on the fly — importing them is what lets the gate compare the
// real key sets instead of regex-scanning source.
import enBundle from "../ui-src/i18n/locales/en";
import zhBundle from "../ui-src/i18n/locales/zh-CN";

const used = collectUsedKeys();
const live = collectDynamicSites();
const failures: string[] = [];

// ---- --update: rebuild the dynamic-key baseline, keeping known reasons ----
if (update) {
  const previous = existsSync(baselinePath) ? loadBaseline() : [];
  const byLine = new Map(previous.map((s) => [`${groupKey(s)}\0${s.line}`, s.reason]));
  const byGroup = new Map<string, string>();
  for (const s of previous) {
    const key = groupKey(s);
    if ((s.reason ?? "").trim() && !byGroup.has(key)) byGroup.set(key, s.reason);
  }
  const sites: BaselineSite[] = live
    .map((s) => ({ ...s, reason: byLine.get(`${groupKey(s)}\0${s.line}`) ?? byGroup.get(groupKey(s)) ?? "" }))
    .sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
  const note =
    "Dynamic i18n key call sites (template literal with ${} / string concatenation) that cannot be resolved statically. " +
    "Generated by `bun scripts/check-i18n-keys.ts --update`; every entry needs a reason. Lines are informational (drift only warns).";
  writeFileSync(baselinePath, `${JSON.stringify({ "//": note, sites }, null, 2)}\n`, "utf8");
  console.log(`动态 key 基线已重建:${sites.length} 处`);
  const missing = sites.filter((s) => !s.reason.trim());
  if (missing.length > 0) {
    console.error(`✗ ${missing.length} 处登记项缺少 reason,请在 ${baselineRel} 里写明为何不能静态化:`);
    for (const s of missing) console.error(`  - ${s.file}:${s.line} 前缀 "${s.prefix}"`);
    process.exit(1);
  }
  process.exit(0);
}

// ---- Half 1: bundle parity (en vs zh-CN) ----
const en = collapsePlurals(flatten(enBundle));
const zh = collapsePlurals(flatten(zhBundle));
for (const key of en) if (!zh.has(key)) failures.push(`zh-CN 缺失: ${key}`);
for (const key of zh) if (!en.has(key)) failures.push(`en 缺失: ${key}`);

// ---- Half 2: every used key must be defined in both ----
for (const { key, file, line } of used) {
  if (!en.has(key)) failures.push(`${file}:${line} 用了未定义的 key: ${key}`);
}

// ---- Half 3: runtime-composed keys must be registered in the baseline ----
let baseline: BaselineSite[] = [];
if (!existsSync(baselinePath)) {
  failures.push(`未找到动态 key 基线 ${baselineRel}(运行 bun scripts/check-i18n-keys.ts --update 生成)`);
} else {
  baseline = loadBaseline();
  for (const s of baseline) {
    if (!s.reason?.trim()) {
      failures.push(`动态 key 登记缺少 reason: ${s.file}:${s.line}(前缀 "${s.prefix}") —— 写明为何不能静态化`);
    }
  }
  const baseGroups = new Map<string, BaselineSite[]>();
  for (const s of baseline) baseGroups.set(groupKey(s), [...(baseGroups.get(groupKey(s)) ?? []), s]);
  const liveGroups = new Map<string, DynSite[]>();
  for (const s of live) liveGroups.set(groupKey(s), [...(liveGroups.get(groupKey(s)) ?? []), s]);

  let drift = 0;
  const unregistered = (s: DynSite) =>
    `未登记的动态 key: ${s.file}:${s.line}(前缀 "${s.prefix}") —— 登记到 ${baselineRel}(写明为何不能静态化),或改成静态 key`;
  const stale = (s: BaselineSite) =>
    `动态 key 登记已失效: ${s.file}:${s.line}(前缀 "${s.prefix}") —— 该处已无对应调用,运行 bun scripts/check-i18n-keys.ts --update 刷新`;

  for (const [key, sites] of liveGroups) {
    const pool = [...(baseGroups.get(key) ?? [])];
    const moved: DynSite[] = [];
    // Same line first, then any site left in the group: that pairing is a
    // shifted line, not a new site.
    for (const site of sites) {
      const i = pool.findIndex((b) => b.line === site.line);
      if (i >= 0) pool.splice(i, 1);
      else moved.push(site);
    }
    for (const site of moved) {
      if (pool.length > 0) {
        pool.shift();
        drift += 1;
      } else {
        failures.push(unregistered(site));
      }
    }
    for (const leftover of pool) failures.push(stale(leftover));
  }
  for (const [key, sites] of baseGroups) {
    if (liveGroups.has(key)) continue;
    for (const leftover of sites) failures.push(stale(leftover));
  }
  if (drift > 0) {
    console.log(`ℹ 动态 key 基线有 ${drift} 处行号漂移(不影响门禁,需要刷新时运行 bun scripts/check-i18n-keys.ts --update)`);
  }
}

if (failures.length > 0) {
  console.error(`✗ i18n key 门禁失败 (${failures.length} 项):`);
  for (const f of failures.slice(0, 40)) console.error(`  - ${f}`);
  if (failures.length > 40) console.error(`  ... 另有 ${failures.length - 40} 项`);
  console.error("  出路:在 ui-src/i18n/locales/ui/*.en.ts 与 *.zh.ts 里补齐对应 key（两个语言包必须同时改）。");
  if (failures.some((f) => f.startsWith("未登记的动态 key") || f.startsWith("动态 key 登记"))) {
    console.error(`  动态 key 另有出路:优先把它改成静态 key;确实无法静态化才登记到 ${baselineRel}。`);
  }
  process.exit(1);
}

console.log(
  `✓ i18n key 门禁通过:调用点 ${used.length} 个,en ${en.size} 个 key,zh-CN ${zh.size} 个 key,两包 key 集合完全一致,动态 key 登记 ${baseline.length} 处全部命中`,
);
