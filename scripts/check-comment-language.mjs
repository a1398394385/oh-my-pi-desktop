#!/usr/bin/env node
// Chinese-comment ratchet gate (open-source i18n wave 1):
// 1. Counts comment lines containing CJK text per directory and compares the
//    counts against the baseline snapshot scripts/comment-language-baseline.json.
//    current > baseline fails the gate; decreases are allowed and encouraged.
// 2. Scope (aggregated per directory): host/ ui-src/ scripts/ src-tauri/src/
//    ui/ (ui/dist excluded) .githooks/ plus root-level source files.
//    Markdown and every non-source extension are never scanned.
// 3. A line counts as a Chinese comment line when the first CJK char appears
//    after the first comment marker on that line (regex heuristic). Known
//    over-counting (Chinese string literal sharing a line with a trailing
//    comment, URLs like https:// before Chinese text) is accepted on purpose:
//    an inflated baseline keeps the ratchet safe to lower later.
// 4. Exemptions: ui-src/i18n/ (locale data, Chinese is data not comments),
//    settings-zh.ts / commands-zh.ts (transitional copies owned by wave B;
//    the entries go stale once those files are deleted) and build outputs
//    (node_modules/dist/target/out/release/coverage path segments).
// Baseline lifecycle: generated by --update, tightened as translation waves
// land, only ever goes down -- raising it requires --update plus a written
// justification in the commit message.
// Usage: node scripts/check-comment-language.mjs [--update]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { extname, resolve } from "node:path";

const root = process.cwd();
const baselinePath = "scripts/comment-language-baseline.json";
const update = process.argv.includes("--update");

// Aggregation directories in stable output order ("(root)" collects root-level source files)
const SCOPE_DIRS = ["host", "ui-src", "scripts", "src-tauri/src", "ui", ".githooks", "(root)"];
const excludedSegments = new Set(["node_modules", "dist", "out", "release", "target", "coverage"]);
const exemptPrefixes = [
  "ui-src/i18n/",
  "ui-src/components/settings/settings-zh.ts",
  "ui-src/components/composer/commands-zh.ts",
];

// Comment markers per file family ("leading*" = block-comment continuation lines starting with *)
const MARKERS = {
  js: ["//", "/*", "leading*"],
  rust: ["//", "/*", "leading*"],
  css: ["/*", "leading*"],
  shell: ["#"],
  html: ["<!--", "//", "/*", "leading*"],
};
const FAMILY_BY_EXT = {
  ".ts": "js",
  ".tsx": "js",
  ".js": "js",
  ".jsx": "js",
  ".mjs": "js",
  ".cjs": "js",
  ".rs": "rust",
  ".css": "css",
  ".scss": "css",
  ".sh": "shell",
  ".html": "html",
  ".htm": "html",
};
const CJK = /[\u4e00-\u9fff]/;

function git(args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trimEnd();
}

// Directory bucket for a repo-relative path, or null when out of scope
function scopeDirOf(filePath) {
  const segments = filePath.split("/");
  if (segments.some((segment) => excludedSegments.has(segment))) return null;
  if (exemptPrefixes.some((prefix) => filePath.startsWith(prefix))) return null;
  if (segments.length === 1) return "(root)";
  for (const dir of SCOPE_DIRS) {
    if (dir !== "(root)" && filePath.startsWith(dir + "/")) return dir;
  }
  return null;
}

// Comment-marker family for a path, or null when not a scannable source file
function familyOf(filePath) {
  const ext = extname(filePath);
  if (ext) return FAMILY_BY_EXT[ext] ?? null;
  // Extensionless hook scripts (e.g. .githooks/pre-commit, scripts/hooks/pre-commit)
  if (/(^|\/)(\.githooks|hooks)\//.test(filePath)) return "shell";
  return null;
}

function firstMarkerIndex(line, family) {
  let best = -1;
  for (const marker of MARKERS[family]) {
    if (marker === "leading*") {
      if (/^\s*\*/.test(line)) best = best === -1 ? line.indexOf("*") : Math.min(best, line.indexOf("*"));
    } else {
      const idx = line.indexOf(marker);
      if (idx !== -1) best = best === -1 ? idx : Math.min(best, idx);
    }
  }
  return best;
}

function countChineseCommentLines(filePath, family) {
  const lines = readFileSync(resolve(root, filePath), "utf8").split("\n");
  let count = 0;
  for (const line of lines) {
    const cjkAt = line.search(CJK);
    if (cjkAt === -1) continue;
    const markerAt = firstMarkerIndex(line, family);
    if (markerAt !== -1 && markerAt < cjkAt) count += 1;
  }
  return count;
}

function loadBaseline() {
  return JSON.parse(readFileSync(resolve(root, baselinePath), "utf8"));
}

// ---- collect current counts ----
const counts = new Map(SCOPE_DIRS.map((dir) => [dir, 0]));
const files = git(["ls-files", "-co", "--exclude-standard"])
  .split("\n")
  .filter(Boolean)
  .map((filePath) => {
    const dir = scopeDirOf(filePath);
    const family = familyOf(filePath);
    return dir && family ? { filePath, dir, family } : null;
  })
  .filter(Boolean);

for (const { filePath, dir, family } of files) {
  counts.set(dir, counts.get(dir) + countChineseCommentLines(filePath, family));
}

// ---- update mode: rewrite the baseline with current values ----
if (update) {
  const snapshot = Object.fromEntries(SCOPE_DIRS.map((dir) => [dir, counts.get(dir)]));
  writeFileSync(resolve(root, baselinePath), JSON.stringify(snapshot, null, 2) + "\n", "utf8");
  console.log(`✓ 中文注释基线已更新(${baselinePath}),新基线供 review:`);
  console.log(JSON.stringify(snapshot, null, 2));
  process.exit(0);
}

// ---- ratchet check against the baseline ----
let baseline;
try {
  baseline = loadBaseline();
} catch {
  console.error(`✗ 中文注释门禁失败:基线 ${baselinePath} 不存在或不可解析,先执行 node scripts/check-comment-language.mjs --update 生成基线`);
  process.exit(1);
}

const failures = [];
let lowered = false;
const summary = SCOPE_DIRS.map((dir) => {
  const base = baseline[dir] ?? 0;
  const current = counts.get(dir);
  if (current > base) failures.push({ dir, base, current });
  if (current < base) lowered = true;
  return `${dir} ${current}/${base}`;
}).join("、");

if (failures.length > 0) {
  console.error(`✗ 中文注释门禁失败(${failures.length} 项,当前/基线,棘轮只许降不许升):`);
  for (const { dir, base, current } of failures) {
    console.error(`  - ${dir} 基线 ${base} → 当前 ${current}(超出 ${current - base})`);
  }
  console.error(`  出路一:新注释一律用英文写(本门禁即「代码注释用英文」规则的机器化)。`);
  console.error(`  出路二:若因文件在目录间迁移等基线漂移而误挂,说明情况后执行 node scripts/check-comment-language.mjs --update 重置基线,并在 commit 描述写明理由。`);
  process.exit(1);
}

console.log(`✓ 中文注释门禁通过:受检源文件 ${files.length} 个;各目录 当前/基线 —— ${summary}`);
if (lowered) console.log(`↓ 存在低于基线的目录,译英落波后可执行 node scripts/check-comment-language.mjs --update 收紧棘轮`);
