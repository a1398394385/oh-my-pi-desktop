// Which changed files nobody wrote by hand: lockfiles, minified/compiled
// output, checked-in dependencies, and files whose header says so. Ported from
// MyGit's internal/generated so the diff can fold them away.
import path from "node:path";

/** Files package managers write, matched on the basename. */
export const GENERATED_NAMES: Readonly<Record<string, true>> = {
  "package-lock.json": true, "npm-shrinkwrap.json": true, "yarn.lock": true,
  "pnpm-lock.yaml": true, "bun.lock": true, "bun.lockb": true, "deno.lock": true,
  "go.sum": true, "go.work.sum": true, "Cargo.lock": true, "Gemfile.lock": true,
  "composer.lock": true, "poetry.lock": true, "Pipfile.lock": true, "uv.lock": true,
  "pdm.lock": true, "flake.lock": true, "Podfile.lock": true, "Package.resolved": true,
  "pubspec.lock": true, "mix.lock": true, "packages.lock.json": true, "gradle.lockfile": true,
};

/** Endings of minified, source-mapped and compiled files. */
export const GENERATED_SUFFIXES: readonly string[] = [
  ".min.js", ".min.mjs", ".min.css", ".js.map", ".css.map",
  ".pb.go", "_pb2.py", "_pb2.pyi", ".pb.swift", ".g.dart", ".freezed.dart",
  ".designer.cs", ".snap",
];

/** Directories holding dependencies checked into the tree. */
export const GENERATED_DIRS: readonly string[] = [
  "node_modules", "vendor", "bower_components", ".yarn", "Pods", "third_party",
];

/** True when the path itself marks the file as generated (no IO). */
export function generatedByName(filePath: string): boolean {
  const base = path.posix.basename(filePath.replace(/\\/g, "/"));
  if (GENERATED_NAMES[base]) return true;
  if (GENERATED_SUFFIXES.some((s) => base.endsWith(s))) return true;
  return filePath.split("/").slice(0, -1).some((dir) => GENERATED_DIRS.includes(dir));
}

/** True when the file's first lines say a tool wrote it. */
export function generatedByHeader(headLines: readonly string[]): boolean {
  return headLines.slice(0, 5).some((l) =>
    l.includes("@generated")
    || (l.includes("Code generated") && l.includes("DO NOT EDIT"))
    || l.includes("<auto-generated"));
}

/** Generated by name, suffix, directory, or the header of its first lines. */
export function isGenerated(filePath: string, headLines: readonly string[]): boolean {
  return generatedByName(filePath) || generatedByHeader(headLines);
}
